function outputFiles = plot_formal_monte_carlo(summaryFile, outputDirectory)
%PLOT_FORMAL_MONTE_CARLO Plot an existing formal summary only.
% This function never reads raw observations or calls inference functions.

if nargin < 1 || isempty(summaryFile)
    formalDirectory = fileparts(mfilename('fullpath'));
    root = fileparts(formalDirectory);
    summaryFile = fullfile(root, 'formal_results', 'summary', ...
        'formal_summary.mat');
end
if nargin < 2 || isempty(outputDirectory)
    outputDirectory = fullfile(fileparts(summaryFile), 'figures');
end
loaded = load(summaryFile, 'summary');
assert(isfield(loaded, 'summary'), 'paperA:MissingSummary', ...
    'Summary file does not contain summary: %s', summaryFile);
summary = loaded.summary;
assert(summary.schemaVersion == 1, 'paperA:SummarySchemaMismatch', ...
    'Unsupported summary schema in %s.', summaryFile);
if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

snrDb = summary.snrDbValues;
outputFiles = strings(0, 1);

fig = figure('Color','w','Name','Position RMSE');
semilogy(snrDb, summary.rmse(:,1), '-o', ...
    snrDb, summary.rmse(:,2), '-s', ...
    snrDb, summary.rmse(:,3), '-d', ...
    snrDb, summary.rmse(:,4), '--o', ...
    snrDb, summary.rmse(:,5), '--s', ...
    snrDb, summary.rmse(:,6), '--d', 'LineWidth',1.3);
grid on; xlabel('SNR (dB)'); ylabel('Conditional RMSE (m)');
title('Comparison A: coarse and refined position RMSE');
legend('Coarse UE1','Coarse UE2','Coarse Joint', ...
    'Refined UE1','Refined UE2','Refined Joint','Location','best');
outputFiles = [outputFiles; export_triplet(fig, outputDirectory, ...
    'formal_position_rmse')]; %#ok<AGROW>

fig = figure('Color','w','Name','Failure Rates');
plot(snrDb, summary.noOutputRate, '-o', ...
    snrDb, summary.finiteNotConvergedRate, '-s', ...
    snrDb, summary.finiteNotConvergedConditionalRate, '--d', ...
    'LineWidth',1.3);
grid on; ylim([0,1]); xlabel('SNR (dB)'); ylabel('Rate');
title('Comparison A: output and convergence status');
legend('No refined output / completed', ...
    'Finite nonconverged / completed', ...
    'Finite nonconverged / finite refined','Location','best');
outputFiles = [outputFiles; export_triplet(fig, outputDirectory, ...
    'formal_failure_rates')]; %#ok<AGROW>

fig = figure('Color','w','Name','Runtime');
plot(snrDb, summary.runtimeMean, '-o', ...
    snrDb, summary.runtimeMedian, '-s', ...
    snrDb, summary.runtimeP95, '-d', ...
    snrDb, summary.runtimeMaximum, '--^', 'LineWidth',1.3);
grid on; xlabel('SNR (dB)'); ylabel('Runtime per trial (s)');
title('Comparison A: runtime statistics');
legend('Mean','Median','95th percentile','Maximum','Location','best');
outputFiles = [outputFiles; export_triplet(fig, outputDirectory, ...
    'formal_runtime_statistics')]; %#ok<AGROW>

fig = figure('Color','w','Name','Joint Error Distribution');
semilogy(snrDb, summary.medianError(:,3), '-o', ...
    snrDb, summary.p95Error(:,3), '-s', ...
    snrDb, summary.maximumError(:,3), '-d', ...
    snrDb, summary.medianError(:,6), '--o', ...
    snrDb, summary.p95Error(:,6), '--s', ...
    snrDb, summary.maximumError(:,6), '--d', 'LineWidth',1.3);
grid on; xlabel('SNR (dB)'); ylabel('Joint error (m)');
title('Comparison A: conditional joint-error distribution');
legend('Coarse median','Coarse p95','Coarse maximum', ...
    'Refined median','Refined p95','Refined maximum','Location','best');
outputFiles = [outputFiles; export_triplet(fig, outputDirectory, ...
    'formal_joint_error_distribution')]; %#ok<AGROW>
end

function files = export_triplet(fig, outputDirectory, stem)
files = [string(fullfile(outputDirectory, [stem,'.png'])); ...
    string(fullfile(outputDirectory, [stem,'.pdf'])); ...
    string(fullfile(outputDirectory, [stem,'.fig']))];
exportgraphics(fig, files(1), 'Resolution', 300);
exportgraphics(fig, files(2), 'ContentType', 'vector');
savefig(fig, files(3));
end
