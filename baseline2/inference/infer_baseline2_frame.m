function result = infer_baseline2_frame( ...
    YSeparated, separatedNoiseVariance, baseReflections, ...
    positionPriorMessage, activeRisIndices, cfg)
%INFER_BASELINE2_FRAME Prior-aided Multi-RIS 3D inference for one frame.
% The externally supplied position prior is used only by the position MAP;
% channel estimation remains identical to Baseline 1.

activeRisIndices = activeRisIndices(:);
channel = estimate_channel_parameters( ...
    YSeparated, separatedNoiseVariance, ...
    baseReflections, activeRisIndices, cfg);

numActiveRis = numel(activeRisIndices);
channelFimResults = cell(numActiveRis, 1);
for activeIndex = 1:numActiveRis
    risIndex = activeRisIndices(activeIndex);
    qHat = [channel.xiEstimate(activeIndex); ...
        channel.zetaEstimate(activeIndex); ...
        cfg.ofdm.subcarrier_spacing * ...
        channel.delayEstimate(activeIndex)];
    channelFimResults{activeIndex} = compute_channel_fim( ...
        qHat, channel.rhoEstimate(activeIndex), ...
        baseReflections(:, :, risIndex), ...
        separatedNoiseVariance, cfg);
end

mapResult = refine_position_map( ...
    channel, channelFimResults, positionPriorMessage, [], ...
    activeRisIndices, cfg);

result.channel = channel;
result.map = mapResult;
result.staticPositionEstimate = mapResult.staticPositionEstimate;
result.mobilePositionEstimate = mapResult.mobilePositionEstimate;
end
